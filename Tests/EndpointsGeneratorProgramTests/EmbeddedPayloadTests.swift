#if OpenAPIGenerator
import Foundation
import Testing
@testable import endpoints_generate

let programRepository = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    .deletingLastPathComponent().deletingLastPathComponent()

@Suite struct EmbeddedPayloadTests {
    @Test func embeddedSourcesMatchTheirAuthorities() throws {
        let dsl = try Data(
            contentsOf: programRepository.appendingPathComponent(
                "Sources/EndpointsGeneratorConfig/EndpointsGeneratorConfig.swift"))
        let transport = try Data(
            contentsOf: programRepository.appendingPathComponent(
                "Sources/endpoints-generate/_EndpointsConfigTransport.swift"))
        let expected = """
            // Generated by UPDATE_EMBEDDED=1 swift test --filter Embedded. Do not edit.
            #if OpenAPIGenerator
            import Foundation
            enum Embedded {
                static let dsl = String(decoding: Data(base64Encoded: "\(dsl.base64EncodedString())")!, as: UTF8.self)
                static let transport = String(decoding: Data(base64Encoded: "\(transport.base64EncodedString())")!, as: UTF8.self)
            }
            #endif

            """
        let file = programRepository.appendingPathComponent(
            "Sources/endpoints-generate/Embedded.swift")
        if ProcessInfo.processInfo.environment["UPDATE_EMBEDDED"] == "1" {
            try Data(expected.utf8).write(to: file)
        } else {
            #expect(Embedded.dsl == String(decoding: dsl, as: UTF8.self))
            #expect(Embedded.transport == String(decoding: transport, as: UTF8.self))
        }
        #expect(try Data(contentsOf: file) == Data(expected.utf8))
    }
}
#endif
